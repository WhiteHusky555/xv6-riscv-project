#include "kernel/types.h"
#include "kernel/stat.h"
#include "user/user.h"

#define ITERATIONS 100

int main() {
    int fd[2];
    int pid;

    printf("[TEST] Запуск проверки состязания kill и sleep...\n");
    printf("[TEST] Выполняется %d итераций. Если тест зависнет - баг не устранен.\n", ITERATIONS);

    for(int i = 0; i < ITERATIONS; i++) {
        // Создаем канал (pipe). Чтение из пустого канала гарантированно вызывает sleep() в ядре.
        if(pipe(fd) < 0) {
            printf("Ошибка создания pipe\n");
            exit(1);
        }

        pid = fork();
        if(pid < 0) {
            printf("Ошибка fork\n");
            exit(1);
        }

        if(pid == 0) {
            // ================= ДОЧЕРНИЙ ПРОЦЕСС =================
            close(fd[1]); // Закрываем конец для записи
            char buf[1];
            
            // Вызов read() заблокируется. В ядре это приведет к:
            // 1. piperead() проверяет p->killed
            // 2. Вызывает sleep()
            read(fd[0], buf, 1);
            
            // Если процесс дошел сюда, значит read() вернул ошибку (так и должно быть)
            // Но в xv6 usertrap убьет процесс еще до возврата в user-space.
            exit(0);
        } else {
            // ================ РОДИТЕЛЬСКИЙ ПРОЦЕСС ================
            close(fd[0]); // Закрываем конец для чтения
            
            // Искусственная задержка (Busy-wait), чтобы ребенок успел зайти в read()
            for(volatile int j = 0; j < 100000; j++);   

            // Отправляем сигнал завершения. 
            // Пытаемся "подловить" дочерний процесс в окне уязвимости.
            kill(pid);

            // Ожидаем завершения ребенка.
            // ЕСЛИ БАГ ЕСТЬ: Ребенок пропустит kill, уснет навсегда, и wait() зависнет.
            // ЕСЛИ БАГ ИСПРАВЛЕН: sleep() заметит p->killed внутри себя и прервется.
            wait(0);
            
            close(fd[1]); // Очищаем ресурсы для следующей итерации
        }
    }

    printf("[TEST] УСПЕХ! Ни один из %d процессов не завис в sleep(). Гонка устранена.\n", ITERATIONS);
    exit(0);
}